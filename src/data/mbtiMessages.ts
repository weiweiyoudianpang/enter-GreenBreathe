// 获取MBTI特定的鼓励语
export function getEncouragementMessage(
  mbtiType: MBTIType,
  taskType: 'hydration' | 'eyeCare' | 'movement'
): string {
  const typeMessages = mbtiMessages[mbtiType]?.[taskType] || [];
  const commonMessages = mbtiMessages.common[taskType] || [];
  
  // 如果该类型有专属消息，优先使用；否则使用通用消息
  const messages = typeMessages.length > 0 ? typeMessages : commonMessages;
  
  if (messages.length === 0) return '记得照顾好自己';
  
  const randomIndex = Math.floor(Math.random() * messages.length);
  return messages[randomIndex];
}
